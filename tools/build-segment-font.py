"""Build original geometric EL-style digit outlines; no third-party font data.

Requires fonttools4.68.0, installed only in the project's ignored cache.
"""
from pathlib import Path
import sys, json, hashlib, math
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'.cache'/'python'))
from fontTools.fontBuilder import FontBuilder
from fontTools.pens.ttGlyphPen import TTGlyphPen
import fontTools

OUT=ROOT/'assets'/'fonts'
OUT.mkdir(parents=True,exist_ok=True)

def horizontal(x,y,w=390,t=65):
    return [(x+t/2,y),(x+w-t/2,y),(x+w,y+t/2),(x+w-t/2,y+t),(x+t/2,y+t),(x,y+t/2)]
def vertical(x,y,h=290,t=65):
    return [(x,y+t/2),(x+t/2,y),(x+t,y+t/2),(x+t,y+h-t/2),(x+t/2,y+h),(x,y+h-t/2)]
def circle(x,y,r):
    return [(x+r*math.cos(a*math.tau/16),y+r*math.sin(a*math.tau/16)) for a in range(16)]
segments={
 'a':horizontal(125,810), 'g':horizontal(125,450), 'd':horizontal(125,90),
 'f':vertical(65,500), 'b':vertical(510,500),
 'e':vertical(65,140), 'c':vertical(510,140),
}
digit_segments=['abcdef','bc','abdeg','abcdg','bcfg','acdfg','acdefg','abc','abcdefg','abcdfg']
shapes={str(i):[segments[s] for s in enabled] for i,enabled in enumerate(digit_segments)}
shapes[' ']=[]
shapes['-']=[horizontal(125,450)]
shapes['+']=[horizontal(125,450),vertical(290,290,390,65)]
shapes['.']=[circle(90,120,38)]
shapes[':']=[circle(90,325,35),circle(90,650,35)]
shapes['?']=[segments[s] for s in 'abge']
names={c:('digit'+c if c.isdigit() else {' ':'space','-':'minus','+':'plus','.':'period',':':'colon','?':'question'}[c]) for c in shapes}
order=['.notdef']+[names[c] for c in sorted(shapes)]
glyphs={}
for character,name in [(None,'.notdef')]+[(c,names[c]) for c in sorted(shapes)]:
    pen=TTGlyphPen(None)
    for polygon in shapes.get(character,[]):
        pen.moveTo(tuple(round(v) for v in polygon[0]))
        for point in polygon[1:]: pen.lineTo(tuple(round(v) for v in point))
        pen.closePath()
    glyphs[name]=pen.glyph()
builder=FontBuilder(1000,isTTF=True)
builder.setupGlyphOrder(order)
builder.setupCharacterMap({ord(c):names[c] for c in shapes})
builder.setupGlyf(glyphs)
builder.setupHorizontalMetrics({name:(220 if name in ['period','colon'] else 650,0) for name in order})
builder.setupHorizontalHeader(ascent=920,descent=-80)
builder.setupNameTable({
 'familyName':'Aquarius Segments','styleName':'Regular',
 'uniqueFontIdentifier':'AquariusSegments1.0','fullName':'Aquarius Segments Regular',
 'psName':'AquariusSegments-Regular','version':'Version1.000',
 'copyright':'Original procedural outlines generated by tools/build-segment-font.py. No third-party glyph data.'
})
builder.setupOS2(sTypoAscender=920,sTypoDescender=-80,usWinAscent=920,usWinDescent=80)
builder.setupPost()
builder.setupMaxp()
builder.font.recalcTimestamp=False
builder.font['head'].created=2082844800
builder.font['head'].modified=2082844800
target=OUT/'aquarius-segments.ttf'
builder.save(target)
(OUT/'provenance.json').write_text(json.dumps({
 'generator':'tools/build-segment-font.py','fontToolsVersion':fontTools.__version__,
 'glyphSource':'Original procedural segment polygons; no third-party typeface.',
 'limitation':'EL-style approximation, not a recovered manufacturing font.',
 'sha256':hashlib.sha256(target.read_bytes()).hexdigest(),
},indent=2)+'\n',encoding='utf-8')
print(target)
